const {chromium}=require(process.env.TTCG_PLAYWRIGHT||'playwright');
const {spawnSync}=require('node:child_process');
const {pathToFileURL}=require('node:url');
const path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 try {
 const page=await browser.newPage({viewport:{width:1440,height:900}}),commands=[],errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.exposeFunction('ttcgCommand',text=>commands.push(text));
 await page.goto(pathToFileURL(path.resolve(process.env.TTCG_UI_ROOT||'TesseraUI','index.html')).href);
 const initial=JSON.parse(spawnSync('/tmp/ttcg-ui-host',{input:'',encoding:'utf8'}).stdout.trim());
 for(const turn of [0,1]) {
  const packet={...initial,session:10+turn,phase:'match',turn,opening:true,settling:true};
  await page.evaluate(s=>window.ttcgState(s),packet);
  assert(await page.locator('#starter-draw').isVisible());
  assert.equal(await page.locator('#starter-draw').getAttribute('data-starter'),String(turn));
  assert(await page.locator('#rule-callout').isHidden());
  assert.equal(await page.locator('.first-turn').count(),0,'Do not reveal the starter before the draw');
  assert.equal(await page.locator('#game .nameplate.active').count(),0);
  assert.equal(await page.locator('#player-hand button:enabled').count(),0);
  assert.equal(commands.filter(c=>c.startsWith('settled ')).length,turn);
  await page.evaluate(()=>window.revealAnimation=document.querySelector('.starter-token').getAnimations()[0]);
  await page.evaluate(s=>window.ttcgState(s),packet);
  assert(await page.evaluate(()=>window.revealAnimation===document.querySelector('.starter-token').getAnimations()[0]),'Duplicate packets must not restart the draw');
  await page.waitForTimeout(850);
  assert(await page.locator('#starter-draw').isVisible());
  const offset=await page.locator('.starter-token').evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).m41);
  assert(turn===0?offset<-110:offset>110,'The reveal resolves toward the selected side');
  await page.screenshot({path:`build/starter-reveal-${turn}.png`});
  await page.waitForFunction(()=>!document.getElementById('rule-callout').hidden);
  assert(await page.locator('#starter-draw').isHidden());
  assert.equal(await page.locator('#rule-callout').innerText(),turn===0?'You start':'Hulda starts');
  assert.equal(await page.locator(`#${turn===0?'player':'rival'}-hand.first-turn`).count(),1);
  assert.equal(await page.locator(`#game .${turn===0?'player':'rival'}-name.first-turn`).count(),1);
  assert.equal(await page.locator('#guided-lesson .first-turn').count(),0);
  assert.equal(await page.locator('#player-hand button:enabled').count(),0);
  const animation=await page.evaluate(()=>{window.firstTurnAnimation=document.querySelector('.hand.first-turn').getAnimations()[0];return !!window.firstTurnAnimation;});
  assert(animation);
  await page.evaluate(s=>window.ttcgState(s),packet);
  assert(await page.evaluate(()=>window.firstTurnAnimation===document.querySelector('.hand.first-turn').getAnimations()[0]),'Duplicate packet must not restart the opening');
  assert.equal(commands.filter(c=>c.startsWith('settled ')).length,turn,'No acknowledgement before animation finishes');
  assert.deepEqual(commands.filter(c=>c.startsWith(`opening ${packet.session} `)),[`opening ${packet.session} 0`],'One sound request at announcement start, despite duplicate packets');
  if(turn===0) await page.screenshot({path:'build/clean-catalog/screenshots/first-turn.png'});
  await page.waitForFunction(()=>document.getElementById('rule-callout').hidden);
  await page.waitForTimeout(50);
  assert.deepEqual(commands.filter(c=>c.startsWith(`settled ${packet.session} `)),[`settled ${packet.session} 0`]);
  assert.equal(await page.locator('.first-turn').count(),0);
  assert.equal(await page.locator('#player-hand [data-placeable="true"]').count(),0,'Wait for native acknowledgement before placement');
  await page.evaluate(s=>window.ttcgState({...s,settling:false,opening:false}),packet);
  assert.equal(await page.locator('#player-hand [data-placeable="true"]').count(),turn===0?5:0);
 }
 const packet={...initial,session:20,phase:'match',turn:0,opening:true,settling:true};
 await page.evaluate(s=>window.ttcgState(s),packet);
 await page.evaluate(()=>window.ttcgReset());
 await page.waitForTimeout(1200);
 assert.equal(commands.filter(c=>c.startsWith('settled ')).length,2,'Canceled opening must not acknowledge another match');
 assert.equal(await page.locator('.first-turn').count(),0);
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.evaluate(s=>window.ttcgState({...s,session:21}),packet);
 assert.equal(await page.locator('.starter-token').evaluate(el=>el.getAnimations().length),0);
 await page.waitForFunction(()=>!document.getElementById('rule-callout').hidden);
 assert.equal(await page.locator('.hand.first-turn').evaluate(el=>el.getAnimations().length),0);
 await page.waitForFunction(()=>document.getElementById('rule-callout').hidden);
 assert.deepEqual(commands.filter(c=>c.startsWith('opening 21 ')),['opening 21 0'],'Reduced motion still plays opening sound once');
 assert.deepEqual(errors,[]);
 console.log('First-turn reveal: both starters, input gating, single acknowledgement, duplicate packets, cancellation and reduced motion passed');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
