#!/usr/bin/env python3
"""Generate native profiles from the authored world roster and collection IDs."""
import json,pathlib,sys
root=pathlib.Path(__file__).resolve().parents[1]
rows=json.loads((root/'data/opponents.json').read_text())
pools={r['name']:r for r in json.loads((root/'data/opponent-collections.json').read_text())['opponents']}
cards={c['form_id']:c for c in json.loads((root/'data/cards.json').read_text())['cards']}
q=lambda s:json.dumps(s,ensure_ascii=False)
lines=['// Generated by tools/build-opponents.py; edit data/opponents.json and opponent-collections.json.',f'inline constexpr std::array<OpponentProfile,{len(rows)}> baseOpponents{{{{']
for p in rows:
 ids=pools[p['name']]['cards'];assert 18<=len(ids)<=32 and all(i in cards for i in ids)
 assert len(set(ids))==len(ids) and 0 not in ids
 vals=[hex(p['base']),q(p['name']),q(p['location']),q(p['skillName']),str(p.get('rules',0)),str(p['skill']),str(p['wager']),'{'+','.join(hex(i) for i in ids)+'}']
 vals += [hex(p[k]) for k in ['reference','knownGlobal']]+[q(p['region'])]
 vals += [hex(p[k]) for k in ['alternateBase','alternateReference']]+[str(p.get('hold',1))]
 vals += [str(p['level']),q(p.get('master','Skyrim.esm'))]
 vals += [str(p.get('traveller',False)).lower(),hex(p.get('signature',0)),hex(p.get('dialogueFaction',0))]
 vals += ['false','false',str(p.get('tournamentEligible',True)).lower(),str(p.get('requiredMaster',True)).lower(),str(p.get('personalRules',False)).lower(),str(p.get('personalTrade',1)),str(p.get('reputationGate',-1)),str(p.get('restock',True)).lower(),str(p.get('spawned',False)).lower()]
 lines.append(' {'+','.join(vals)+'},')
lines+=['}};',''];text='\n'.join(lines);path=root/'include/OpponentProfiles.inc'
if '--check' in sys.argv:assert path.read_text()==text,'Regenerate opponent profiles'
else:path.write_text(text)
print(f'{len(rows)} authored opponent collections verified')

layout=json.loads((root/'data/free-play-record-layout.json').read_text())
by_base={r['base']:r for r in layout['records']}
header=['#pragma once','#include <array>','#include <cstdint>','namespace ttcg {','struct EncounterRecord { std::uint32_t base,accept,decline; };']
for key,value in layout.items():
 if key in ('childAccept','alternateAccept','alternateDecline'):header.append(f'inline constexpr std::uint32_t encounter_{key}={hex(value)};')
header.append(f'inline constexpr std::array<EncounterRecord,{len(rows)}> encounterRecords{{{{')
for p in rows:
 r=by_base[p['base']];header.append(' {'+','.join(hex(r[k]) for k in ('base','accept','decline'))+'},')
header+=['}};','}'];target=root/'include/EncounterRecords.h';text='\n'.join(header)+'\n'
if '--check' in sys.argv:assert target.read_text()==text,'Regenerate encounter records'
else:target.write_text(text)
