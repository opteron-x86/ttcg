/* Shared by the official roster workshop and the expansion editor. The lookup
   tables are generated by card_rank_policy.py, not a second set of JS rules. */
'use strict';
function createTesseraRankTools(data) {
 const bitmaps = new Map(), pools = new Map();
 const cost = card => card.sides.reduce((sum,n) => sum + (data.policy.rank_costs[n] || 0),0);
 function validRanks(card) {
  if (!data.rankChecks[card.tier] || card.sides.length !== 4 || card.sides.some(n => !Number.isInteger(n) || n < 1 || n > 10)) return false;
  const kind = card.rarity === 'Common' ? 'Common' : 'Other', key = card.tier + kind;
  if (!bitmaps.has(key)) bitmaps.set(key,Uint8Array.from(atob(data.rankChecks[card.tier][kind]),c => c.charCodeAt(0)));
  const index = card.sides.reduce((n,side) => n * 10 + side - 1,0);
  return Boolean(bitmaps.get(key)[index >> 3] & (1 << (index % 8)));
 }
 function randomProfiles(card) {
  const key = card.tier + ':' + card.rarity;
  if (pools.has(key)) return pools.get(key);
  const policy = data.policy.tiers.find(p => p.tier === card.tier);
  if (!policy) return [];
  const profiles = data.workshopPolicy.profiles[card.tier], common = profiles.Common || [], examples = profiles[card.rarity] || [];
  let low = policy.weighted_min, high = policy.weighted_max, peak = policy.side_max;
  if (card.rarity !== 'Legendary' && examples.length) {
   high = Math.max(...examples.map(sides => cost({sides})));
   peak = Math.max(...examples.flat());
   if (card.rarity !== 'Common' && common.length) low = Math.max(low,Math.max(...common.map(sides => cost({sides}))) + 1);
  }
  const pool = [];
  for (let top = 1; top <= peak; top++) for (let right = 1; right <= peak; right++)
   for (let bottom = 1; bottom <= peak; bottom++) for (let left = 1; left <= peak; left++) {
    const sides = [top,right,bottom,left], candidate = {tier:card.tier,rarity:card.rarity,sides}, points = cost(candidate);
    if (points < low || points > high || (card.rarity === 'Epic' && Math.max(...sides) !== peak)) continue;
    if (validRanks(candidate)) pool.push(sides);
   }
  pools.set(key,pool); return pool;
 }
 function pickRandomSides(card, used = new Set()) {
  const choices = randomProfiles(card).filter(sides => sides.join() !== card.sides.join());
  const distinct = choices.filter(sides => !used.has(sides.join()));
  const pool = distinct.length ? distinct : choices;
  return pool.length ? [...pool[Math.floor(Math.random() * pool.length)]] : null;
 }
 return {cost,validRanks,randomProfiles,pickRandomSides};
}
if (typeof module !== 'undefined') module.exports = createTesseraRankTools;
